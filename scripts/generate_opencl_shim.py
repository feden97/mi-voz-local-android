"""Generate typed, optional OpenCL forwarding functions from the pinned headers.

The shim has a different SONAME from the vendor's libOpenCL.so. It never supplies
fake successful GPU results: an unavailable driver exposes no OpenCL platforms,
so the CPU backend can continue working without a hard vendor dependency.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

PREAMBLE = '''// Generated by scripts/generate_opencl_shim.py; do not edit wrappers by hand.
// GGML revision: eced84c86f8b012c752c016f7fe789adea168e1e
// Uses the official Khronos declarations, including callback calling conventions.
// OpenCL declarations: Copyright (c) 2008-2020 The Khronos Group Inc.
// Licensed under Apache-2.0; see assets/licenses/OpenCL-Headers.txt.
#define CL_TARGET_OPENCL_VERSION 300
#define CL_USE_DEPRECATED_OPENCL_1_0_APIS
#define CL_USE_DEPRECATED_OPENCL_1_1_APIS
#define CL_USE_DEPRECATED_OPENCL_1_2_APIS
#define CL_USE_DEPRECATED_OPENCL_2_0_APIS
#define CL_USE_DEPRECATED_OPENCL_2_1_APIS
#define CL_USE_DEPRECATED_OPENCL_2_2_APIS
#include <CL/cl.h>
#include <CL/cl_ext.h>
#include <android/log.h>
#include <dlfcn.h>

namespace {
void * vendor_library() {
    // C++ static initialization is synchronized. The loaded driver deliberately
    // lives until process exit; cached function pointers must never dangle.
    static void * const handle = []() -> void * {
        const char * names[] = {
            "libOpenCL.so", "libOpenCL-car.so", "libOpenCL-pixel.so",
            "/vendor/lib64/libOpenCL.so",
        };
        for (const char * name : names) {
            void * candidate = dlopen(name, RTLD_NOW | RTLD_LOCAL);
            if (!candidate) continue;
            void * entry = dlsym(candidate, "clGetPlatformIDs");
            Dl_info own_library{};
            Dl_info entry_library{};
            const bool same_library = dladdr(reinterpret_cast<void *>(&vendor_library), &own_library) &&
                entry && dladdr(entry, &entry_library) && own_library.dli_fbase == entry_library.dli_fbase;
            if (!entry || same_library) {
                dlclose(candidate);
                continue;
            }
            __android_log_print(ANDROID_LOG_INFO, "MiVozOpenCL", "Loaded vendor OpenCL: %s", name);
            return candidate;
        }
        __android_log_print(ANDROID_LOG_WARN, "MiVozOpenCL", "Vendor OpenCL unavailable; CPU remains available");
        return nullptr;
    }();
    return handle;
}

template <typename Function> Function vendor_function(const char * name) {
    void * handle = vendor_library();
    void * address = handle ? dlsym(handle, name) : nullptr;
    if (handle && !address) {
        __android_log_print(ANDROID_LOG_WARN, "MiVozOpenCL", "Vendor OpenCL entry point unavailable: %s", name);
    }
    return reinterpret_cast<Function>(address);
}
} // namespace

extern "C" {
'''


def remove_comments(value: str) -> str:
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", value, flags=re.S)


def matching_parenthesis(value: str, start: int) -> int:
    depth = 0
    for index in range(start, len(value)):
        if value[index] == "(":
            depth += 1
        elif value[index] == ")":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError("Unbalanced OpenCL function declaration")


def declarations(headers: str) -> dict[str, tuple[str, str]]:
    result: dict[str, tuple[str, str]] = {}
    headers = remove_comments(headers)
    pattern = re.compile(r"extern\s+CL_API_ENTRY\s+([\w\s*]+?)\s+CL_API_CALL\s+(cl\w+)\s*\(")
    for match in pattern.finditer(headers):
        end = matching_parenthesis(headers, match.end() - 1)
        return_type = " ".join(re.sub(r"\bCL_API_PREFIX__\w+\b", "", match.group(1)).split())
        parameters = headers[match.end():end].strip()
        result[match.group(2)] = (return_type, parameters)
    return result


def arguments(parameters: str) -> list[str]:
    if parameters in ("", "void"):
        return []
    values: list[str] = []
    depth = 0
    start = 0
    for index, character in enumerate(parameters + ","):
        if character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
        elif character == "," and depth == 0:
            parameter = parameters[start:index].strip()
            callback = re.search(r"\(\s*(?:CL_CALLBACK\s*)?\*\s*(\w+)\s*\)", parameter)
            name = callback.group(1) if callback else re.search(r"(\w+)\s*(?:\[[^\]]*\])?\s*$", parameter).group(1)
            values.append(name)
            start = index + 1
    return values


def generate(headers: str, source: str) -> tuple[str, list[str]]:
    available = declarations(headers)
    used = sorted(set(re.findall(r"\b(cl[A-Z]\w*)\s*\(", remove_comments(source))))
    missing = [name for name in used if name not in available]
    if missing:
        raise ValueError("No official OpenCL prototype found for: " + ", ".join(missing))
    wrappers: list[str] = []
    for name in used:
        return_type, parameters = available[name]
        names = arguments(parameters)
        prototype = "\n    ".join(line.strip() for line in parameters.splitlines())
        fallback = []
        if "errcode_ret" in names:
            fallback.append("if (errcode_ret) *errcode_ret = CL_INVALID_OPERATION;")
        if name == "clGetPlatformIDs":
            fallback += ["if (num_platforms) *num_platforms = 0;", "return CL_PLATFORM_NOT_FOUND_KHR;"]
        elif return_type == "cl_int":
            fallback.append("return CL_INVALID_OPERATION;")
        elif return_type == "void":
            fallback.append("return;")
        elif "*" in return_type or return_type in {
            "cl_context", "cl_command_queue", "cl_mem", "cl_program", "cl_kernel", "cl_event", "cl_sampler",
        }:
            fallback.append("return nullptr;")
        else:
            raise ValueError(f"Unreviewed fallback return type {return_type!r} for {name}")
        prefix = "" if return_type == "void" else "return "
        wrappers.append(
            f"CL_API_ENTRY {return_type} CL_API_CALL {name}(\n    {prototype}\n) {{\n"
            f"    static auto function = vendor_function<decltype(&::{name})>(\"{name}\");\n"
            f"    if (!function) {{\n        " + "\n        ".join(fallback) + "\n    }\n"
            f"    {prefix}function({', '.join(names)});\n}}\n"
        )
    source_hash = hashlib.sha256(source.encode("utf-8")).hexdigest()
    output = PREAMBLE + f"// OpenCL source SHA-256: {source_hash}\n\n" + "\n".join(wrappers) + "} // extern C\n"
    return output, used


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--headers-dir", type=Path, default=ROOT / "build/opencl-sdk/OpenCL-Headers")
    parser.add_argument("--ggml-source", type=Path, default=ROOT / "external/qwen3-tts.cpp/ggml/src/ggml-opencl/ggml-opencl.cpp")
    parser.add_argument("--output", type=Path, default=ROOT / "app/src/main/cpp/mivoz_opencl.cpp")
    args = parser.parse_args()
    headers = "\n".join((args.headers_dir / "CL" / name).read_text(encoding="utf-8") for name in ("cl.h", "cl_ext.h"))
    output, used = generate(headers, args.ggml_source.read_text(encoding="utf-8"))
    if not args.output.is_file() or args.output.read_text(encoding="utf-8") != output:
        args.output.write_text(output, encoding="utf-8", newline="\n")
    print(f"Generated {len(used)} typed optional OpenCL entry points: {args.output}")


if __name__ == "__main__":
    main()
